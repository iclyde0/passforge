List<Map<String, dynamic>> simpleBank(String examId, String regulator, List<List<dynamic>> rows) {
  return [
    for (var i = 0; i < rows.length; i++)
      q(
        examId: examId,
        n: i + 1,
        subject: rows[i][0] as String,
        topic: rows[i][1] as String,
        difficulty: rows[i][2] as String,
        stem: rows[i][3] as String,
        choices: (rows[i][4] as List).cast<String>(),
        correct: rows[i][5] as int,
        explanation: rows[i][6] as String,
        regulator: regulator,
      ),
  ];
}

List<Map<String, dynamic>> rowsToQuestions(
  String examId,
  String regulator,
  List<List<dynamic>> rows, {
  int startN = 1,
}) {
  return [
    for (var i = 0; i < rows.length; i++)
      q(
        examId: examId,
        n: startN + i,
        subject: rows[i][0] as String,
        topic: rows[i][1] as String,
        difficulty: rows[i][2] as String,
        stem: rows[i][3] as String,
        choices: (rows[i][4] as List).cast<String>(),
        correct: rows[i][5] as int,
        explanation: rows[i][6] as String,
        regulator: regulator,
      ),
  ];
}

/// Merge core + supplements and renumber IDs. Prints difficulty pool sizes.
List<Map<String, dynamic>> finalizeBank(
  String examId,
  String regulator,
  List<Map<String, dynamic>> core,
  List<List<dynamic>> supplementRows,
) {
  final seenStems = <String>{};
  final merged = <Map<String, dynamic>>[];
  for (final item in [...core, ...rowsToQuestions(examId, regulator, supplementRows)]) {
    final stem = (item['stem'] as String).trim().toLowerCase();
    if (!seenStems.add(stem)) continue;
    merged.add(item);
  }
  final out = <Map<String, dynamic>>[];
  for (var i = 0; i < merged.length; i++) {
    final m = Map<String, dynamic>.from(merged[i]);
    m['id'] = '$examId-${(i + 1).toString().padLeft(4, '0')}';
    out.add(m);
  }
  final counts = <String, int>{'easy': 0, 'medium': 0, 'hard': 0};
  for (final q in out) {
    final d = q['difficulty'] as String;
    counts[d] = (counts[d] ?? 0) + 1;
  }
  stdout.writeln(
    '  $examId pools → easy=${counts['easy']}, medium=${counts['medium']}, hard=${counts['hard']} (total ${out.length})',
  );
  return out;
}

