Map<String, dynamic> q({
  required String examId,
  required int n,
  required String subject,
  required String topic,
  required String difficulty,
  required String stem,
  required List<String> choices,
  required int correct,
  required String explanation,
  String regulator = 'PRC',
}) {
  assert(correct >= 0 && correct < choices.length);
  return {
    'id': '$examId-${n.toString().padLeft(4, '0')}',
    'examId': examId,
    'region': 'PH',
    'subject': subject,
    'topic': topic,
    'difficulty': difficulty,
    'stem': stem,
    'choices': choices,
    'correctIndex': correct,
    'explanation': explanation,
    'country': 'Philippines',
    'regulator': regulator,
  };
}

void writeExam(Directory out, String examId, String title, List<Map<String, dynamic>> questions) {
  for (final item in questions) {
    assert(item['examId'] == examId);
    assert(item['region'] == 'PH');
  }
  final payload = {
    'examId': examId,
    'title': title,
    'country': 'Philippines',
    'region': 'PH',
    'disclaimer':
        'Original practice items for educational simulation only. Not affiliated with PRC/CSC.',
    'questionCount': questions.length,
    'questions': questions,
  };
  final path = File('${out.path}${Platform.pathSeparator}$examId.json');
  path.writeAsStringSync(const JsonEncoder.withIndent('  ').convert(payload));
  stdout.writeln('Wrote ${path.path} (${questions.length} questions)');
}

