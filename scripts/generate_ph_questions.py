def q(
    exam_id: str,
    n: int,
    subject: str,
    topic: str,
    difficulty: str,
    stem: str,
    choices: list[str],
    correct: int,
    explanation: str,
) -> dict:
    assert 0 <= correct < len(choices)
    return {
        "id": f"{exam_id}-{n:04d}",
        "examId": exam_id,
        "region": "PH",
        "subject": subject,
        "topic": topic,
        "difficulty": difficulty,
        "stem": stem,
        "choices": choices,
        "correctIndex": correct,
        "explanation": explanation,
        "country": "Philippines",
        "regulator": "PRC" if exam_id != "cse" else "CSC",
    }


