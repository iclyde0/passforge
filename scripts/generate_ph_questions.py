def write_exam(exam_id: str, title: str, questions: list[dict]) -> None:
    for item in questions:
        assert item["examId"] == exam_id
        assert item["region"] == "PH"
        assert item["country"] == "Philippines"
    payload = {
        "examId": exam_id,
        "title": title,
        "country": "Philippines",
        "region": "PH",
        "disclaimer": "Original practice items for educational simulation only. Not affiliated with PRC/CSC.",
        "questionCount": len(questions),
        "questions": questions,
    }
    path = OUT / f"{exam_id}.json"
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"Wrote {path} ({len(questions)} questions)")


